--대출 정보 등록
CREATE TABLE loan (
    loan_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    copy_id BIGINT NOT NULL,
    member_user_id BIGINT,
    checked_out_by_user_id BIGINT NOT NULL,
    borrowed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    initial_due_date DATE NOT NULL DEFAULT ((CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul')::date + 14),
    current_due_date DATE NOT NULL DEFAULT ((CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul')::date + 14),
    returned_at TIMESTAMPTZ,
    returned_by_user_id BIGINT,
    is_cancelled BOOLEAN NOT NULL DEFAULT FALSE,
    cancelled_at TIMESTAMPTZ,

    CONSTRAINT pk_loan PRIMARY KEY (loan_id),
    CONSTRAINT fk_loan_member FOREIGN KEY (member_user_id)
        REFERENCES app_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_loan_copy FOREIGN KEY (copy_id)
        REFERENCES book_copy (copy_id) ON DELETE RESTRICT,
    CONSTRAINT fk_loan_checked_out_by FOREIGN KEY (checked_out_by_user_id)
        REFERENCES app_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_loan_returned_by FOREIGN KEY (returned_by_user_id)
        REFERENCES app_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_loan_dates CHECK (
        initial_due_date = (borrowed_at AT TIME ZONE 'Asia/Seoul')::date + 14
    ),
    CONSTRAINT ck_loan_date_order CHECK (
        current_due_date >= initial_due_date
    ),
    CONSTRAINT ck_loan_return_time CHECK (returned_at >= borrowed_at),
    CONSTRAINT ck_loan_return_actor_pair CHECK (
        (returned_at IS NULL) = (returned_by_user_id IS NULL)
    ),
    CONSTRAINT ck_loan_cancel_pair CHECK (
        (is_cancelled = FALSE AND cancelled_at IS NULL)
        OR
        (is_cancelled = TRUE AND cancelled_at IS NOT NULL)
    )
);

