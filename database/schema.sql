-- ============================================================
-- 트리거: "이전 값 -> 새 값"을 비교해야 하는 규칙 (CHECK 로는 표현 불가)
-- 에러는 23514(check_violation) + CONSTRAINT 이름으로 통일해서
-- 백엔드가 일반 CHECK 위반과 같은 방식(제약 이름)으로 처리할 수 있게 한다.
-- ============================================================

-- 계정 역할은 생성 후 변경 불가
CREATE FUNCTION fn_app_user_role_immutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '계정 역할은 변경할 수 없습니다 (user_id=%, % -> %)',
        OLD.user_id, OLD.role, NEW.role
        USING ERRCODE = 'check_violation',
              CONSTRAINT = 'trg_app_user_role_immutable';
END;
$$;

CREATE TRIGGER trg_app_user_role_immutable
    BEFORE UPDATE ON app_user
    FOR EACH ROW
    WHEN (OLD.role IS DISTINCT FROM NEW.role)
    EXECUTE FUNCTION fn_app_user_role_immutable();

-- 탈퇴(WITHDRAWN)는 최종 상태: 다른 상태로 되돌릴 수 없음
CREATE FUNCTION fn_app_user_withdrawal_final() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '탈퇴한 계정은 다시 활성화할 수 없습니다 (user_id=%)',
        OLD.user_id
        USING ERRCODE = 'check_violation',
              CONSTRAINT = 'trg_app_user_withdrawal_final';
END;
$$;

CREATE TRIGGER trg_app_user_withdrawal_final
    BEFORE UPDATE ON app_user
    FOR EACH ROW
    WHEN (OLD.account_status = 'WITHDRAWN'
          AND NEW.account_status IS DISTINCT FROM 'WITHDRAWN')
    EXECUTE FUNCTION fn_app_user_withdrawal_final();

-- 제적(RETIRED)은 최종 상태: 다른 상태로 되돌릴 수 없음
CREATE FUNCTION fn_book_copy_retired_final() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '제적된 소장본은 다른 상태로 바꿀 수 없습니다 (copy_id=%)',
        OLD.copy_id
        USING ERRCODE = 'check_violation',
              CONSTRAINT = 'trg_book_copy_retired_final';
END;
$$;

CREATE TRIGGER trg_book_copy_retired_final
    BEFORE UPDATE ON book_copy
    FOR EACH ROW
    WHEN (OLD.management_status = 'RETIRED'
          AND NEW.management_status IS DISTINCT FROM 'RETIRED')
    EXECUTE FUNCTION fn_book_copy_retired_final();

-- 신규 대출은 "회원 있음 + 미반납 + 미취소 + 미연장" 상태로만 등록
CREATE FUNCTION fn_loan_new_insert_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.member_user_id IS NULL THEN
        RAISE EXCEPTION '신규 대출에는 회원이 지정되어야 합니다'
            USING ERRCODE = 'check_violation',
                  CONSTRAINT = 'trg_loan_new_insert_guard';
    END IF;

    IF NEW.returned_at IS NOT NULL
       OR NEW.returned_by_user_id IS NOT NULL
       OR NEW.is_cancelled THEN
        RAISE EXCEPTION '신규 대출은 반납·취소된 상태로 등록할 수 없습니다'
            USING ERRCODE = 'check_violation',
                  CONSTRAINT = 'trg_loan_new_insert_guard';
    END IF;

    IF NEW.current_due_date <> NEW.initial_due_date THEN
        RAISE EXCEPTION '신규 대출의 현재 만기일은 최초 만기일과 같아야 합니다 (연장은 loan_renewal 로)'
            USING ERRCODE = 'check_violation',
                  CONSTRAINT = 'trg_loan_new_insert_guard';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_loan_new_insert_guard
    BEFORE INSERT ON loan
    FOR EACH ROW
    EXECUTE FUNCTION fn_loan_new_insert_guard();

-- 연체 일수: KST 날짜 기준, 만기일 당일은 0일
CREATE FUNCTION fn_overdue_days(p_due_date DATE, p_at TIMESTAMPTZ)
RETURNS INTEGER
LANGUAGE sql IMMUTABLE STRICT
RETURN GREATEST(0, (p_at AT TIME ZONE 'Asia/Seoul')::date - p_due_date);

-- 반납 1건의 정지 종료시각: 반납 확정시각 + 연체 일수 x 24시간 (연체 아니면 NULL)
CREATE FUNCTION fn_suspension_end(p_returned_at TIMESTAMPTZ, p_due_date DATE)
RETURNS TIMESTAMPTZ
LANGUAGE sql IMMUTABLE STRICT
RETURN p_returned_at
       + NULLIF(fn_overdue_days(p_due_date, p_returned_at), 0) * INTERVAL '24 hours';

-- 회원 정지 종료시각 재계산: 취소되지 않은 반납 대출 중 가장 늦은 값 (합산 아님)
CREATE FUNCTION fn_member_suspension_until(p_member_user_id BIGINT)
RETURNS TIMESTAMPTZ
LANGUAGE sql STABLE STRICT
RETURN (
    SELECT max(fn_suspension_end(l.returned_at, l.current_due_date))
    FROM loan l
    WHERE l.member_user_id = p_member_user_id
      AND l.is_cancelled = FALSE
      AND l.returned_at IS NOT NULL
);

-- 소장본별 대출 가능 여부 (ACTIVE + 유효한 미반납 대출 없음)
CREATE VIEW v_copy_availability AS
SELECT c.copy_id,
       c.book_id,
       c.copy_code,
       c.management_status,
       l.loan_id          AS current_loan_id,
       l.current_due_date AS current_due_date,
       (c.management_status = 'ACTIVE' AND l.loan_id IS NULL) AS is_available
FROM book_copy c
LEFT JOIN loan l
       ON l.copy_id = c.copy_id
      AND l.is_cancelled = FALSE
      AND l.returned_at IS NULL;

-- 도서별 소장본 수·대출 가능 수·일반 공개 여부
CREATE VIEW v_book_availability AS
SELECT b.book_id,
       count(a.copy_id)                                              AS total_copies,
       count(a.copy_id) FILTER (WHERE a.management_status <> 'RETIRED') AS holding_copies,
       count(a.copy_id) FILTER (WHERE a.is_available)                AS available_copies,
       bool_or(a.management_status <> 'RETIRED') IS TRUE             AS is_public
FROM book b
LEFT JOIN v_copy_availability a ON a.book_id = b.book_id
GROUP BY b.book_id;

-- 현재 유효한 미반납 대출의 연체 현황 (DOC-12)
CREATE VIEW v_active_loan_status AS
SELECT l.loan_id,
       l.member_user_id,
       l.copy_id,
       l.borrowed_at,
       l.current_due_date,
       (r.loan_id IS NOT NULL)                                AS is_renewed,
       fn_overdue_days(l.current_due_date, CURRENT_TIMESTAMP) AS overdue_days,
       fn_overdue_days(l.current_due_date, CURRENT_TIMESTAMP) > 0 AS is_overdue
FROM loan l
LEFT JOIN loan_renewal r ON r.loan_id = l.loan_id
WHERE l.is_cancelled = FALSE
  AND l.returned_at IS NULL;

