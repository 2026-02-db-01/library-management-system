-- 도서관 대출·반납·연체 관리 시스템
-- 03-03 물리적 데이터 모델 / PostgreSQL
-- 최초 설치용 DDL. 기존 데이터베이스에 대한 마이그레이션 스크립트가 아니다.
-- 설계 원칙: ISBN-13(하이픈 제거), 실물 소장본 단위 대출,
--           대출·반납 처리 사서 이력, 연장 이력 보존, 데이터 삭제 제한.

-- 1. 회원·사서·관리자 계정
CREATE TABLE app_user (
    user_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    login_id        VARCHAR(50)  NOT NULL,
    password_hash   TEXT         NOT NULL,
    full_name       VARCHAR(100) NOT NULL,
    contact         VARCHAR(50),
    role            VARCHAR(16)  NOT NULL,
    account_status  VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_app_user PRIMARY KEY (user_id),
    CONSTRAINT uq_app_user_login_id UNIQUE (login_id),
    CONSTRAINT ck_app_user_login_id_nonblank CHECK (btrim(login_id) <> ''),
    CONSTRAINT ck_app_user_full_name_nonblank CHECK (btrim(full_name) <> ''),
    CONSTRAINT ck_app_user_role CHECK (role IN ('MEMBER', 'LIBRARIAN', 'ADMIN')),
    CONSTRAINT ck_app_user_account_status CHECK (account_status IN ('ACTIVE', 'INACTIVE'))
);

-- 2. 서지정보: 같은 ISBN-13은 하나의 BOOK 행에 대응한다.
-- ISBN-10 -> ISBN-13 변환, 하이픈 제거, ISBN-13 체크디지트 검증은
-- 저장 전 서비스 계층에서 수행한다. DB는 숫자 13자리 형식을 재검증한다.
CREATE TABLE book (
    book_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    isbn             VARCHAR(13)  NOT NULL,
    title            VARCHAR(255) NOT NULL,
    publisher        VARCHAR(150),
    publication_year SMALLINT,
    catalog_status   VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',

    CONSTRAINT pk_book PRIMARY KEY (book_id),
    CONSTRAINT uq_book_isbn UNIQUE (isbn),
    CONSTRAINT ck_book_isbn13_format CHECK (isbn ~ '^[0-9]{13}$'),
    CONSTRAINT ck_book_title_nonblank CHECK (btrim(title) <> ''),
    CONSTRAINT ck_book_publication_year CHECK (
        publication_year IS NULL OR publication_year BETWEEN 1 AND 9999
    ),
    CONSTRAINT ck_book_catalog_status CHECK (catalog_status IN ('ACTIVE', 'RETIRED'))
);

-- 3. 저자: 동명이인 허용. author_name에는 UNIQUE를 적용하지 않는다.
CREATE TABLE author (
    author_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    author_name VARCHAR(150) NOT NULL,

    CONSTRAINT pk_author PRIMARY KEY (author_id),
    CONSTRAINT ck_author_name_nonblank CHECK (btrim(author_name) <> '')
);

-- 4. 도서와 저자의 다대다 관계
CREATE TABLE book_author (
    book_id   BIGINT NOT NULL,
    author_id BIGINT NOT NULL,

    CONSTRAINT pk_book_author PRIMARY KEY (book_id, author_id),
    CONSTRAINT fk_book_author_book FOREIGN KEY (book_id)
        REFERENCES book (book_id) ON DELETE RESTRICT,
    CONSTRAINT fk_book_author_author FOREIGN KEY (author_id)
        REFERENCES author (author_id) ON DELETE RESTRICT
);

-- 5. 실제로 대출되는 개별 실물 소장본
-- 대출 중인지는 management_status가 아닌 미반납 LOAN으로 판단한다.
CREATE TABLE book_copy (
    copy_id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    book_id            BIGINT      NOT NULL,
    copy_code          VARCHAR(50) NOT NULL,
    management_status  VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',

    CONSTRAINT pk_book_copy PRIMARY KEY (copy_id),
    CONSTRAINT uq_book_copy_code UNIQUE (copy_code),
    CONSTRAINT ck_book_copy_code_nonblank CHECK (btrim(copy_code) <> ''),
    CONSTRAINT ck_book_copy_management_status CHECK (
        management_status IN ('ACTIVE', 'RETIRED')
    ),
    CONSTRAINT fk_book_copy_book FOREIGN KEY (book_id)
        REFERENCES book (book_id) ON DELETE RESTRICT
);

-- 6. 대출과 반납의 변경 불가능한 업무 식별자 및 처리자 이력
-- checked_out_by_user_id: 대출 처리 사서 (필수)
-- returned_by_user_id: 반납 처리 사서 (미반납이면 NULL)
-- 사서 역할·활성 상태·요청한 로그인 사용자와의 일치는 서비스에서 검증한다.
CREATE TABLE loan (
    loan_id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    member_user_id          BIGINT      NOT NULL,
    copy_id                 BIGINT      NOT NULL,
    checked_out_by_user_id  BIGINT      NOT NULL,
    borrowed_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    initial_due_date        DATE        NOT NULL,
    current_due_date        DATE        NOT NULL,
    returned_at             TIMESTAMPTZ,
    returned_by_user_id     BIGINT,

    CONSTRAINT pk_loan PRIMARY KEY (loan_id),
    CONSTRAINT fk_loan_member FOREIGN KEY (member_user_id)
        REFERENCES app_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_loan_copy FOREIGN KEY (copy_id)
        REFERENCES book_copy (copy_id) ON DELETE RESTRICT,
    CONSTRAINT fk_loan_checkout_librarian FOREIGN KEY (checked_out_by_user_id)
        REFERENCES app_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_loan_return_librarian FOREIGN KEY (returned_by_user_id)
        REFERENCES app_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_loan_due_date_order CHECK (current_due_date >= initial_due_date),
    CONSTRAINT ck_loan_return_time CHECK (
        returned_at IS NULL OR returned_at >= borrowed_at
    ),
    CONSTRAINT ck_loan_return_actor_pair CHECK (
        (returned_at IS NULL AND returned_by_user_id IS NULL)
        OR
        (returned_at IS NOT NULL AND returned_by_user_id IS NOT NULL)
    )
);

-- 7. 성공한 대출 연장 사건. 정책상 1회지만 향후 정책 변경을 위해
-- loan_id를 UNIQUE로 묶지 않는다. 횟수·기간·연체 여부는 서비스에서 검증한다.
CREATE TABLE loan_renewal (
    renewal_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    loan_id           BIGINT      NOT NULL,
    renewed_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    previous_due_date DATE        NOT NULL,
    new_due_date      DATE        NOT NULL,

    CONSTRAINT pk_loan_renewal PRIMARY KEY (renewal_id),
    CONSTRAINT fk_loan_renewal_loan FOREIGN KEY (loan_id)
        REFERENCES loan (loan_id) ON DELETE RESTRICT,
    CONSTRAINT ck_loan_renewal_due_date_order CHECK (
        new_due_date > previous_due_date
    )
);

-- 대출 중인 회원은 동시에 1건, 소장본도 동시에 1건만 허용한다.
-- 반납된 과거 기록은 보존하며 재대출할 수 있다.
CREATE UNIQUE INDEX uq_loan_active_member
    ON loan (member_user_id) WHERE returned_at IS NULL;
CREATE UNIQUE INDEX uq_loan_active_copy
    ON loan (copy_id) WHERE returned_at IS NULL;

-- FK 탐색·회원별 이력·연체 조회·사서별 업무 이력에 필요한 인덱스
-- UNIQUE 제약에 의해 자동 생성되는 인덱스는 중복 생성하지 않는다.
CREATE INDEX idx_book_author_author_id ON book_author (author_id);
CREATE INDEX idx_book_copy_book_id ON book_copy (book_id);
CREATE INDEX idx_loan_member_history ON loan (member_user_id, borrowed_at DESC);
CREATE INDEX idx_loan_copy_history ON loan (copy_id, borrowed_at DESC);
CREATE INDEX idx_loan_checkout_librarian ON loan (checked_out_by_user_id);
CREATE INDEX idx_loan_return_librarian ON loan (returned_by_user_id)
    WHERE returned_by_user_id IS NOT NULL;
CREATE INDEX idx_loan_active_due_date ON loan (current_due_date)
    WHERE returned_at IS NULL;
CREATE INDEX idx_loan_renewal_history ON loan_renewal (loan_id, renewed_at DESC);

-- 운영 규칙(서비스 계층):
-- A. ISBN은 13자리 정규화·체크디지트 검증 후 저장한다.
-- B. MEMBER만 대출 대상이고 LIBRARIAN만 대출·반납 처리할 수 있다.
--    사서 ID는 요청 본문이 아닌 인증된 로그인 세션에서 취득한다.
-- C. 대출 기간 14일: (borrowed_at AT TIME ZONE 'Asia/Seoul')::date + 14.
-- D. 연장 1회, 비연체·미반납일 때만: 기존 current_due_date + 7.
--    LOAN의 current_due_date UPDATE와 LOAN_RENEWAL INSERT는 한 트랜잭션.
-- E. 반납 시 returned_at과 returned_by_user_id를 같은 UPDATE로 기록한다.
-- F. 연체 판정: 미반납이며 current_due_date <
--    (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul')::date.
-- G. 대출/반납/연장은 행 잠금 및 트랜잭션으로 경쟁 상태를 방지한다.
-- H. 회원 비활성화는 미반납 대출이 없을 때만 허용한다.
