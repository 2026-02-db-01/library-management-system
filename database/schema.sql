CREATE TABLE app_user(
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    login_id VARCHAR(50),
    password_hash TEXT,
    full_name VARCHAR(100),
    contact VARCHAR(11),
    role VARCHAR(16) NOT NULL,
    account_status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    borrowing_suspended_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_app_user PRIMARY KEY (user_id),
    CONSTRAINT uq_app_user_login_id UNIQUE (login_id),
    CONSTRAINT ck_app_user_role CHECK (role IN ('MEMBER', 'LIBRARIAN', 'ADMIN')),
    CONSTRAINT ck_app_user_role_status CHECK (
        (role = 'MEMBER' AND account_status IN ('ACTIVE', 'WITHDRAWN'))
        OR
        (role IN ('LIBRARIAN', 'ADMIN') AND account_status IN ('ACTIVE', 'INACTIVE'))
    ),
    CONSTRAINT ck_app_user_contact_format CHECK (contact ~ '^[0-9]{10,11}$'),
    CONSTRAINT ck_app_user_login_id_nonblank CHECK (btrim(login_id) <> ''),
    CONSTRAINT ck_app_user_full_name_nonblank CHECK (btrim(full_name) <> ''),
    CONSTRAINT ck_app_user_personal_data_lifecycle CHECK (
        (account_status <> 'WITHDRAWN'
         AND login_id IS NOT NULL AND password_hash IS NOT NULL
         AND full_name IS NOT NULL AND contact IS NOT NULL)
        OR
        (account_status = 'WITHDRAWN'
         AND login_id IS NULL AND password_hash IS NULL
         AND full_name IS NULL AND contact IS NULL
         AND borrowing_suspended_until IS NULL)
    )
);

CREATE UNIQUE INDEX uq_app_user_active_member_contact ON app_user (contact) WHERE role = 'MEMBER' AND account_status = 'ACTIVE';

