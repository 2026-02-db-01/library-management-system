const pk = (name: string, columns: string[]) => ({
  name,
  kind: 'PRIMARY KEY' as const,
  columns,
  definition: `PRIMARY KEY (${columns.join(', ')})`,
  purpose: '각 행을 유일하게 식별합니다.',
})

const fk = (name: string, column: string, reference: string, role: string) => ({
  name,
  kind: 'FOREIGN KEY' as const,
  columns: [column],
  definition: `FOREIGN KEY (${column}) REFERENCES ${reference} ON DELETE RESTRICT`,
  purpose: `${role} 참조를 보존하며 연결된 행의 물리 삭제를 제한합니다.`,
  reference,
})

const unique = (name: string, column: string, purpose: string) => ({
  name,
  kind: 'UNIQUE' as const,
  columns: [column],
  definition: `UNIQUE (${column})`,
  purpose,
})

